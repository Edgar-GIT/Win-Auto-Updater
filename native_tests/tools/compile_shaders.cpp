// Build-time helper (not part of SingleUpdate.exe): compiles the HLSL in
// ../gpu_shaders.hpp with D3DCompile and writes ../gpu_shader_bytecode.inc, so
// the GPU test ships ready-made shader bytecode and never has to compile on the
// machine under test.
//
//   compile_shaders.exe <output.inc>
//
// Run it with Microsoft's d3dcompiler_47.dll next to the exe (see
// compile_shaders.sh) so the blobs come from the reference compiler.

#include <windows.h>

#include <d3dcommon.h>

#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

#include "../gpu_shaders.hpp"

namespace {

using CompileFn = HRESULT(WINAPI*)(LPCVOID, SIZE_T, LPCSTR, const D3D_SHADER_MACRO*, ID3DInclude*, LPCSTR,
                                   LPCSTR, UINT, UINT, ID3DBlob**, ID3DBlob**);

constexpr UINT kOptimizationLevel3 = 1U << 15;

struct Target {
    const char* entry;
    const char* profile;
    const char* arrayName;
};

bool compile(CompileFn fn, const Target& target, std::vector<unsigned char>* out) {
    ID3DBlob* blob = nullptr;
    ID3DBlob* messages = nullptr;
    const DWORD begin = GetTickCount();
    const HRESULT hr = fn(nt::kGpuShaderSource, std::strlen(nt::kGpuShaderSource), "void_burner.hlsl",
                          nullptr, nullptr, target.entry, target.profile, kOptimizationLevel3, 0, &blob,
                          &messages);
    const DWORD elapsed = GetTickCount() - begin;
    if (messages != nullptr) {
        std::printf("%s messages:\n%.*s\n", target.entry, static_cast<int>(messages->GetBufferSize()),
                    static_cast<const char*>(messages->GetBufferPointer()));
        messages->Release();
    }
    if (FAILED(hr) || blob == nullptr) {
        std::printf("FAILED %s (%s): 0x%08lX\n", target.entry, target.profile,
                    static_cast<unsigned long>(hr));
        return false;
    }
    const auto* bytes = static_cast<const unsigned char*>(blob->GetBufferPointer());
    out->assign(bytes, bytes + blob->GetBufferSize());
    blob->Release();
    std::printf("ok     %-8s %-7s %6zu bytes  %lu ms\n", target.entry, target.profile, out->size(),
                static_cast<unsigned long>(elapsed));
    return true;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        std::printf("usage: compile_shaders.exe <output.inc>\n");
        return 2;
    }

    HMODULE module = LoadLibraryW(L"d3dcompiler_47.dll");
    if (module == nullptr) {
        std::printf("d3dcompiler_47.dll not found\n");
        return 1;
    }
    wchar_t path[MAX_PATH]{};
    GetModuleFileNameW(module, path, MAX_PATH);
    std::printf("compiler: %ls\n", path);
    const auto fn = reinterpret_cast<CompileFn>(
        reinterpret_cast<void (*)()>(GetProcAddress(module, "D3DCompile")));
    if (fn == nullptr) {
        std::printf("D3DCompile not exported\n");
        return 1;
    }

    const Target targets[] = {
        {"VSMain", "vs_4_0", "kVertex"},
        {"PSScene", "ps_4_0", "kScene"},
        {"PSBlit", "ps_4_0", "kBlit"},
    };

    std::string text =
        "// Generated by native_tests/tools/compile_shaders — do not edit.\n"
        "// Direct3D shader bytecode (vs_4_0 / ps_4_0) of the HLSL in gpu_shaders.hpp.\n"
        "// Regenerate after changing the shader: native_tests/tools/compile_shaders.sh\n\n"
        "namespace nt::bytecode {\n\n";
    for (const Target& target : targets) {
        std::vector<unsigned char> blob;
        if (!compile(fn, target, &blob)) {
            return 1;
        }
        text += "inline const unsigned char ";
        text += target.arrayName;
        text += "[] = {";
        char item[8];
        for (size_t i = 0; i < blob.size(); ++i) {
            if (i % 20 == 0) {
                text += "\n    ";
            }
            std::snprintf(item, sizeof(item), "%u,", static_cast<unsigned>(blob[i]));
            text += item;
        }
        text += "\n};\n\n";
    }
    text += "}  // namespace nt::bytecode\n";

    std::FILE* file = std::fopen(argv[1], "wb");
    if (file == nullptr) {
        std::printf("cannot write %s\n", argv[1]);
        return 1;
    }
    std::fwrite(text.data(), 1, text.size(), file);
    std::fclose(file);
    std::printf("wrote %s\n", argv[1]);
    return 0;
}
